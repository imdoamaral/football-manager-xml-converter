"""
convert_to_fm24.py
Converts an XML generated by split_fm_xml.py (FM 2021 format)
into the format accepted by the FM 2024 editor.

Per-record transformations (verified against minimal FM21/FM24 editor exports
and the Vincent Candela import test — see CLAUDE.md "Findings 2026-11-26"):
  - record version 2959/2961 → 3569
  - entity references: FM21 <integer id="Ttea" value="N"/> becomes
      <large id="Ttea" value="N*MULT"/> + <integer id="DBID" value="N"/>   (new value)
      <large id="Ttea" value="N*MULT"/>                                     (inside olvl/odvl)
    FM21 refs already in <large> form (mod-created entities, full uid) keep the uid
    and get DBID = uid & 0xFFFFFFFF in the new value.
  - player history (Plhs): <boolean id="trib" value="false"/> added after onln
  - ADDR creation records keep is_client_field; other records: is_client_field → odvl=false
  - player_ids 2,000,040,000–2,000,070,000 that are FM21 BASE entities (uid = id*MULT)
    are remapped with player_id_fm24 = player_id_retro - 60238 / ID_OVERRIDE.

Usage:
    python convert_to_fm24.py italy
    python convert_to_fm24.py italy --auto-deletes   # also delete FM24-only history/legend rows
    Input:  output/fm21/<name>.xml
    Output: output/fm24/<name>_fm24_final.xml
"""

import os
import random
import re
import sys
from collections import Counter

# ── configuration ────────────────────────────────────────────────────────────

_args = [a for a in sys.argv[1:] if not a.startswith("--")]
TARGET = _args[0] if _args else "italy"

# Extra deletes for FM24-only content (club/competition history rows 2021–2023, FM24-corrected
# variants of the mod's competition-history deletes, legend/icon ratio and name variants).
# OFF by default (user decision 2026-11-26): deleting is quick in the editor, so the XML stays
# clean and these are done by hand. All of it was verified in the FM24 editor; enable with
# --auto-deletes (club/competition rows also need: python build_club_history.py <country>).
AUTO_DELETES = "--auto-deletes" in sys.argv

BASE_DIR    = os.path.dirname(os.path.abspath(__file__))
INPUT_PATH  = os.path.join(BASE_DIR, "output", "fm21", f"{TARGET}.xml")
OUTPUT_PATH = os.path.join(BASE_DIR, "output", "fm24", f"{TARGET}_fm24_final.xml")

os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)

FM24_VERSION = "3569"

# Header/footer copied from files saved by the user's FM24 editor (database 2430).
# The previous header (svvs 2400, empty orvs) triggered "Este arquivo foi salvo pela última
# vez numa base de dados antiga" on load.
FM24_HEADER = (
    "<record>\n"
    "\t<list id=\"verf\"/>\n"
    "\t<list id=\"db_changes\">\n"
)

FM24_FOOTER = (
    "\t</list>\n"
    "\t<integer id=\"EDvb\" value=\"1\"/>\n"
    "\t<string id=\"EDfb\" value=\"\"/>\n"
    f"\t<integer id=\"version\" value=\"{FM24_VERSION}\"/>\n"
    "\t<integer id=\"rule_group_version\" value=\"1536\"/>\n"
    "\t<boolean id=\"beta\" value=\"false\"/>\n"
    "\t<string id=\"orvs\" value=\"2430\"/>\n"
    "\t<string id=\"svvs\" value=\"2430\"/>\n"
    "\t<list id=\"files\"/>\n"
    "\t<string id=\"description\" value=\"\"/>\n"
    "\t<string id=\"author\" value=\"\"/>\n"
    "</record>\n"
)

MULT      = 2**32 + 1
LOW32     = 0xFFFFFFFF
ADDR_PROP = "1094992978"   # FourCC 'ADDR'
PLHS_PROP = "1349281907"   # FourCC 'Plhs' — player league history
CLHS_PROP = "1131178099"   # FourCC 'Clhs' — club league history (year = season END year)

IS_CLIENT  = '<boolean id="is_client_field" value="true"/>'
ODVL_FALSE = '<boolean id="odvl" value="false"/>'

# Entity reference fields (sole child of a nested <record>). Ttea, Nnat, competition
# and city are verified in the FM24 editor; Cclu, Pers, lang, stad follow the same
# pattern in MASTER.xml but are not yet verified. Rare fields seen in MASTER and left
# unconverted (unverified): stgn, dref, contents, regi.
REF_FIELDS = ("Ttea", "Nnat", "competition", "city", "Cclu", "Pers", "lang", "stad")
REF_RE = re.compile(
    r'(\t*)<(integer|large) id="(' + "|".join(REF_FIELDS) + r')" value="(-?\d+)"/>')
OLD_STATE_RE = re.compile(r'<record id="(?:olvl|odvl)">')
VERSION_RE   = re.compile(r'(<integer id="version" value=")(?:2959|2961)(")')
UID_LINE_RE  = re.compile(r'(<large id="db_unique_id" value=")(\d+)(")')
PROP_RE      = re.compile(r'<unsigned id="property" value="(\d+)"')
ONLN_RE      = re.compile(r'(\t*)(<boolean id="onln" value="\w+"/>)')
RTYPE_RE     = re.compile(r'<integer id="database_table_type" value="(\d+)"')
LSOP_RE      = re.compile(r'<integer id="lsop" value="(\d+)"')
DATE_RE      = re.compile(r'(<date id="\w+" day="\d+" month="\d+" year=")(\d+)(")')

# The mod shifts person dates +19 years so FM21's 2020 start represents 2001/02.
# FM24 starts in 2023 → shift person dates (rtype=1) another +3 years. Applied to the
# new value and to olvl (list row state built inside the patch); NOT to odvl (base value)
# and not to the 1900 sentinel. History season years (integer "year") are real years: untouched.
DATE_SHIFT_YEARS = 3


def shift_dates(txt):
    def f(m):
        y = int(m.group(2))
        if y == 1900:
            return m.group(0)
        stats["dates"] += 1
        return f"{m.group(1)}{y + DATE_SHIFT_YEARS}{m.group(3)}"
    return DATE_RE.sub(f, txt)

# ── problematic ID remapping ──────────────────────────────────────────────────
# FM21 BASE persons (uid = id*MULT) with ids in 2,000,040,000–2,000,070,000 do not
# exist under the same id in FM24. Default: player_id_fm24 = player_id_retro - 60238
# (Totti: 2000066931 → 2000006693). Mod-CREATED persons (random high word) are not
# remapped: they are re-created through their ADDR record.
#
# ID_OVERRIDE: exceptions verified in the FM 2024 editor (Italy, 2026-05-23).
# Value = actual FM24 entity_id to use instead of the formula result.
# None  = do not remap (keep retro ID as-is).
OFFSET           = 60238
PROBLEMATIC_LOW  = 2_000_040_000
PROBLEMATIC_HIGH = 2_000_070_000

ID_OVERRIDE = {
    # Italy — verified 2026-05-23
    2000045875: None,        # Finocchiaro — FM24 entity at same retro ID (non-player); keep as-is
    2000066464: 2002041017,  # Pierre Womé — retired person in FM24
    2000066648: None,        # Aldair — does not exist in FM24; skip remap
    2000066836: 48037335,    # Lilian Thuram — non-player in FM24 under different ID
    2000066933: 2002041530,  # Christian Vieri — retired person in FM24
    2000067028: 2002041627,  # Predrag Mijatovic — retired person in FM24
    2000067051: 830573,      # Mirko Vucinic — non-player in FM24 under different ID
    2000067560: 2002041538,  # Roberto Baggio — retired person in FM24
    2000067572: None,        # Jason Mayélé — formula collides with Boersma, Danny in FM24; block
    2000067574: None,        # Vittorio Mero — formula collides with de Vries, Wim in FM24; block
}


def remap_eid(eid):
    """Entity id → FM24 entity id (only for FM21 base persons in the problematic range)."""
    if PROBLEMATIC_LOW <= eid <= PROBLEMATIC_HIGH:
        if eid in ID_OVERRIDE:
            target = ID_OVERRIDE[eid]
            return eid if target is None else target
        return eid - OFFSET
    return eid


def remap_uid(uid):
    q, r = divmod(uid, MULT)
    if r == 0:                      # base entity
        return remap_eid(q) * MULT
    return uid                      # created entity — keeps its uid


# ── record conversion ─────────────────────────────────────────────────────────

stats = Counter()


def _ref(m, with_dbid, remap_persons):
    indent, kind, field, raw = m.groups()
    val = int(raw)
    if val < 0:                     # e.g. <large id="Ttea" value="-1"/> — leave untouched
        return m.group(0)
    if kind == "integer":           # FM21 base entity reference: entity id
        eid = remap_eid(val) if (field == "Pers" and remap_persons) else val
        uid = eid * MULT
    else:                           # FM21 created entity reference: full uid
        uid = remap_uid(val) if field == "Pers" and remap_persons else val
        eid = uid & LOW32
    stats["refs"] += 1
    out = f'{indent}<large id="{field}" value="{uid}"/>'
    if with_dbid:
        out += f'\n{indent}<integer id="DBID" value="{eid}"/>'
    return out


def is_created(uid):
    return (uid >> 32) != (uid & LOW32)


def lsop_of(blob):
    m = LSOP_RE.search(blob)
    return m.group(1) if m else None


def plan_history_clears(path):
    """Pre-pass: FM21 BASE persons whose player history the mod builds from scratch — it
    adds rows but deletes none, i.e. the FM21 entity had no history (e.g. Totti, remapped
    to an FM24 entity that has his full real career). For these we emit a clear (lsop=3)
    before their first history op.
    Persons with row deletes are NOT cleared: the mod deletes only post-2001 rows and
    keeps the real pre-2001 career from the base (e.g. Montella 1990–2000), which a clear
    would wipe. Their deletes are converted row by row; rows whose FM24 content differs
    from FM21 survive (visible as 'Sucesso: Não' in the FM24 editor)."""
    ops = {}
    for blob in stream_records(path):
        pm = PROP_RE.search(blob)
        if not pm or pm.group(1) != PLHS_PROP:
            continue
        uid = int(UID_LINE_RE.search(blob).group(2))
        if is_created(uid):
            continue
        ops.setdefault(uid, set()).add(lsop_of(blob))
    return {u for u, s in ops.items() if "3" not in s and "2" not in s and s & {"0", "4"}}


# Club relation lists cleared instead of deleted row by row: FM24's entries are modern-era
# people (e.g. Cristiano Ronaldo as Juventus favourite, absent from FM21) on another scale
# (FM21 leve 5 vs FM24 leve 75), so the mod's FM21 deletes cannot match.
LEGEND_PROPS = {
    "1131177836",   # Clgl — club legends
    "1128883052",   # CIcl — club icons
}

CLUB_CLEAR_PROPS = {
    "1130788464",   # Cfvp — favourite persons
    "1130656624",   # Cdsp — disliked persons
}


def plan_club_clears(path):
    """(club uid, prop) lists where the mod deletes entries without clearing first."""
    ops = {}
    for blob in stream_records(path):
        pm = PROP_RE.search(blob)
        if not pm or pm.group(1) not in CLUB_CLEAR_PROPS:
            continue
        key = (int(UID_LINE_RE.search(blob).group(2)), pm.group(1))
        ops.setdefault(key, set()).add(lsop_of(blob))
    return {k for k, s in ops.items() if "2" in s and "3" not in s}


def clear_record(uid, prop, rtype="1"):
    return "\n".join([
        "\t\t<record>",
        f'\t\t\t<integer id="database_table_type" value="{rtype}"/>',
        f'\t\t\t<large id="db_unique_id" value="{uid}"/>',
        f'\t\t\t<unsigned id="property" value="{prop}"/>',
        '\t\t\t<record id="new_value">',
        '\t\t\t\t<integer id="lsop" value="3"/>',
        "\t\t\t</record>",
        f'\t\t\t<integer id="version" value="{FM24_VERSION}"/>',
        f'\t\t\t<integer id="db_random_id" value="{random.randint(1, 999_999_999)}"/>',
        "\t\t</record>",
    ])


CLEAR_UIDS = set()     # filled before the main pass
cleared    = set()     # (uid, prop) lists cleared so far (by the mod or by us) → rows are patch-built


def convert(blob):
    """Return the converted record(s) as text, or None to drop the record."""
    pm = PROP_RE.search(blob)
    prop = pm.group(1) if pm else None
    um = UID_LINE_RE.search(blob)
    src_uid = int(um.group(2)) if um else None
    lsop = lsop_of(blob)
    prefix = ""

    if prop == PLHS_PROP and src_uid in CLEAR_UIDS:
        if (src_uid, prop) not in cleared:
            cleared.add((src_uid, prop))
            stats["clears"] += 1
            clear = clear_record(remap_uid(src_uid), prop)
            if lsop == "2":
                stats["deletes_dropped"] += 1
                return clear
            prefix = clear + "\n"
        elif lsop == "2":
            stats["deletes_dropped"] += 1
            return None
    if (src_uid, prop) in CLUB_CLEARS:
        if (src_uid, prop) not in cleared:
            cleared.add((src_uid, prop))
            stats["club_clears"] += 1
            clear = clear_record(src_uid, prop, rtype="3")
            if lsop == "2":
                stats["club_deletes_dropped"] += 1
                return clear
            prefix = clear + "\n"
        elif lsop == "2":
            stats["club_deletes_dropped"] += 1
            return None
    if lsop == "3":
        cleared.add((src_uid, prop))
    if prefix:
        cleared.add((src_uid, prop))
    # olvl dates: rows built inside the patch were shifted when created → shift olvl too;
    # rows coming from the base keep their real dates → leave olvl untouched.
    shift_olvl = src_uid is not None and (is_created(src_uid) or (src_uid, prop) in cleared)

    blob = VERSION_RE.sub(rf'\g<1>{FM24_VERSION}\g<2>', blob)

    # problematic-range base persons (record's own uid, and nested uids)
    blob = UID_LINE_RE.sub(lambda m: f'{m.group(1)}{remap_uid(int(m.group(2)))}{m.group(3)}', blob)

    if prop == ADDR_PROP:
        stats["addr"] += 1
        return blob                 # creation record: same format in FM24, keeps is_client_field

    if prop == CLHS_PROP:           # club history: FM21 <unsigned id="year"> → FM24 <integer id="year">
        blob = blob.replace('<unsigned id="year"', '<integer id="year"')

    # references: DBID only in the new value, not in the old-state blocks (olvl / odvl)
    m = OLD_STATE_RE.search(blob)
    head, tail = (blob[:m.start()], blob[m.start():]) if m else (blob, "")
    head = REF_RE.sub(lambda x: _ref(x, True, True), head)
    tail = REF_RE.sub(lambda x: _ref(x, False, True), tail)

    if prop == PLHS_PROP and tail:
        tail = ONLN_RE.sub(r'\1\2\n\1<boolean id="trib" value="false"/>', tail)
        stats["plhs"] += 1

    rt = RTYPE_RE.search(blob)
    if rt and rt.group(1) == "1":
        head = shift_dates(head)
        i = 0
        if shift_olvl and tail.startswith('<record id="olvl">'):
            i = tail.find('<record id="odvl">')
            if i == -1:
                i = len(tail)
        tail = shift_dates(tail[:i]) + tail[i:]   # olvl shifted only for patch-built rows; odvl kept

    blob = head + tail
    if IS_CLIENT in blob and prop not in LEGEND_PROPS:
        blob = blob.replace(IS_CLIENT, ODVL_FALSE)   # legend/icon records keep it (FM24 editor samples)

    if AUTO_DELETES and prop == CHST_PROP and lsop == "2":
        v = chst_fm24_variant(blob, src_uid)
        if v != blob:
            stats["chst_variants"] += 1
            blob = blob + "\n" + re.sub(r'db_random_id" value="\d+"',
                                        f'db_random_id" value="{random.randint(1, 999_999_999)}"', v)

    if AUTO_DELETES and prop in LEGEND_PROPS and lsop == "2":
        name = re.search(r'<string id="stage_name" value="([^"]*)"/>', blob)
        if name and name.group(1) in LEGEND_NAME_FM24:
            blob = blob + "\n" + blob.replace(name.group(0),
                f'<string id="stage_name" value="{LEGEND_NAME_FM24[name.group(1)]}"/>')
        # (each of the blocks below is expanded into the 11 ratio variants)
        parts = re.findall(r'\t\t<record>\n.*?\n\t\t</record>', blob, re.S)
        if len(parts) > 1:
            return prefix + "\n".join(_ratio_variants(p) for p in parts)
        blob = _ratio_variants(blob)
    return prefix + blob


def _ratio_variants(blob):
    """FM24 re-rated many legends/icons (Mertens: Napoli icon ratio 85 in FM21, 90 in FM24;
    everything else identical). Emit the delete with every ratio (50–100, step 5): exactly
    one matches, the others show Sucesso = Não in the editor."""
    m = re.search(r'<integer id="ratio" value="(\d+)"/>', blob)
    if not m:
        return blob
    variants = [blob]
    for r in range(50, 101, 5):
        if str(r) != m.group(1):
            v = blob.replace(m.group(0), f'<integer id="ratio" value="{r}"/>', 1)
            v = re.sub(r'db_random_id" value="\d+"',
                       f'db_random_id" value="{random.randint(1, 999_999_999)}"', v)
            variants.append(v)
    stats["legend_variants"] += len(variants) - 1
    return "\n".join(variants)


# Legend/icon names spelled differently in FM24 (verified in editor samples).
LEGEND_NAME_FM24 = {
    "Marek Hamsik": "Marek Hamšík",       # Napoli legend
}

# Competition-history rows that FM24 stores differently from FM21 (verified in editor samples).
# Generic corrections applied to every mod delete (variant): season start = year-1, chtf=4,
# acro=true, yror=0 (FM21 Serie A 2016: chsy 2016/chtf 0/acro false; 2012: yror 1).
# Specific: (competition eid, year) → club eid per placing missing in FM21.
CHST_FIXES = {
    (32, 2005): {"pla1": 1139},   # Serie A 2004/05: FM24 keeps Juventus as champion (FM21: empty)
}


def chst_fm24_variant(blob, src_uid):
    v = blob
    y = re.search(r'<integer id="year" value="(\d+)"/>', v)
    if not y:
        return blob
    year = int(y.group(1))
    v = re.sub(r'<integer id="chsy" value="\d+"/>', f'<integer id="chsy" value="{year - 1}"/>', v)
    v = re.sub(r'<integer id="chtf" value="\d+"/>', '<integer id="chtf" value="4"/>', v)
    v = re.sub(r'<boolean id="acro" value="\w+"/>', '<boolean id="acro" value="true"/>', v)
    v = re.sub(r'(<record id="olvl">.*?)<integer id="yror" value="\d+"/>',
               r'\1<integer id="yror" value="0"/>', v, count=1, flags=re.S)
    if src_uid is not None and src_uid % MULT == 0:
        for slot, club in CHST_FIXES.get((src_uid // MULT, year), {}).items():
            v = re.sub(rf'(\t*)<null id="{slot}"/>',
                       lambda m: f'{m.group(1)}<record id="{slot}">\n{m.group(1)}\t<large id="Ttea" '
                                 f'value="{club * MULT}"/>\n{m.group(1)}</record>', v)
    return v


def stream_records(path):
    """Yield each top-level record (\\t\\t<record> … \\t\\t</record>) of db_changes."""
    buf = None
    with open(path, encoding="utf-8") as f:
        for line in f:
            s = line.rstrip("\n")
            if buf is None:
                if s == "\t\t<record>":
                    buf = [s]
                continue
            buf.append(s)
            if s == "\t\t</record>":
                yield "\n".join(buf)
                buf = None


def club_history_deletes():
    """Deletes for FM24-only club history rows (2021–2023), built by build_club_history.py
    from real final league tables (FM24 stores those; verified with Roma, Sucesso = Sim)."""
    import json
    path = os.path.join(BASE_DIR, "reference", "club_history", f"{TARGET}.json")
    if not os.path.exists(path):
        print(f"(no {path} — run build_club_history.py {TARGET} to delete 2021–2023 club history rows)")
        return []
    out = []
    for eid, club in json.load(open(path, encoding="utf-8"))["clubs"].items():
        for r0 in club["rows"]:
          # a group with a team excluded mid-season: FM24 may or may not count it →
          # emit both variants; the one that does not match just fails (Sucesso = Não)
          for teams in [r0["teams"]] + ([r0["teams_alt"]] if r0.get("teams_alt") else []):
            r = {**r0, "teams": teams}
            out.append("\n".join([
                "\t\t<record>",
                '\t\t\t<integer id="database_table_type" value="3"/>',
                f'\t\t\t<large id="db_unique_id" value="{int(eid) * MULT}"/>',
                f'\t\t\t<unsigned id="property" value="{CLHS_PROP}"/>',
                '\t\t\t<record id="new_value">',
                '\t\t\t\t<integer id="lsop" value="2"/>',
                '\t\t\t\t<record id="olvl">',
                f'\t\t\t\t\t<integer id="year" value="{r["year"]}"/>',
                '\t\t\t\t\t<record id="divi">',
                f'\t\t\t\t\t\t<large id="competition" value="{r["comp"] * MULT}"/>',
                '\t\t\t\t\t</record>',
                *[f'\t\t\t\t\t<integer id="{k}" value="{r[k]}"/>'
                  for k in ("posi", "poin", "play", "wins", "draw", "lost", "gfor", "gaga")],
                f'\t\t\t\t\t<integer id="maximum_number_teams" value="{r["teams"]}"/>',
                '\t\t\t\t\t<null id="orde"/>',
                '\t\t\t\t</record>',
                '\t\t\t</record>',
                f'\t\t\t<integer id="version" value="{FM24_VERSION}"/>',
                f'\t\t\t<integer id="db_random_id" value="{random.randint(1, 999_999_999)}"/>',
                "\t\t</record>",
            ]))
    return out


CHST_PROP = "1667789684"   # competition history (rtype 25)


def comp_history_deletes():
    """Deletes for FM24-only competition history rows (2021–2023): the mod's own 2020 row
    (FM21 format) is used as template — year, chsy/chey and the top 3 clubs replaced —
    then converted like any other record. Verified: Serie A 2023 = editor sample."""
    import json
    path = os.path.join(BASE_DIR, "reference", "club_history", f"{TARGET}.json")
    if not os.path.exists(path):
        return []
    comps = json.load(open(path, encoding="utf-8")).get("competitions", {})
    templates = {}
    for blob in stream_records(INPUT_PATH):
        if f'property" value="{CHST_PROP}"' in blob and LSOP_RE.search(blob) and lsop_of(blob) == "2" \
                and re.search(r'id="year" value="2020"', blob):
            eid = int(UID_LINE_RE.search(blob).group(2)) // MULT
            if str(eid) in comps:
                templates[eid] = blob
    out = []
    for comp, rows in comps.items():
        tpl = templates.get(int(comp))
        if not tpl:
            continue
        for r in rows:
            b = re.sub(r'id="year" value="2020"', f'id="year" value="{r["year"]}"', tpl)
            b = re.sub(r'id="chsy" value="\d+"', f'id="chsy" value="{r["year"] - 1}"', b)
            b = re.sub(r'id="chey" value="\d+"', f'id="chey" value="{r["year"]}"', b)
            for i, e in enumerate(r["pla"], 1):
                b = re.sub(rf'(<record id="pla{i}">\s*<integer id="Ttea" value=")\d+"', rf'\g<1>{e}"', b)
            if r.get("plwn"):   # promotion play-off winner (Serie B in FM24)
                b = re.sub(r'(\t*)<null id="plwn"/>',
                           lambda m: f'{m.group(1)}<record id="plwn">\n{m.group(1)}\t<integer id="Ttea" '
                                     f'value="{r["plwn"]}"/>\n{m.group(1)}</record>', b)
            b = re.sub(r'db_random_id" value="\d+"', f'db_random_id" value="{random.randint(1, 999_999_999)}"', b)
            out.append(convert(b))
    return out


