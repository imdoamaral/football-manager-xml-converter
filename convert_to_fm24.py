def plan_promotions(path):
    """FM21-BASE persons (no ADDR in the patch) → dcty for a creation record.

    Some of them no longer exist in FM24 (e.g. Assunção, Mancini), so all their records are
    dropped. Emitting an ADDR for every base person fixes that without knowing who is missing:
    verified 2026-11-26 that an ADDR for a person who EXISTS in FM24 (De Rossi) is harmless
    (no duplicate, FM24 data intact), while for a missing one (Assunção) it creates him.
    dcty: 2 = player (has history or ability), 1 = non-player."""
    seen, player, created = {}, set(), set()
    for blob in stream_records(path):
        pm = PROP_RE.search(blob)
        if pm and pm.group(1) == ADDR_PROP:
            created.add(int(UID_LINE_RE.findall(blob)[-1][1]))
            continue
        rt = RTYPE_RE.search(blob)
        if not rt or rt.group(1) != "1" or not pm or pm.group(1) == DELE_PROP:
            continue
        uid = int(UID_LINE_RE.search(blob).group(2))
        if is_created(uid):
            continue
        seen.setdefault(uid, None)
        if PLAYER_HINT.search(blob) or '<integer id="PD' in blob:
            player.add(uid)
        if pm.group(1) in NAME_PROPS and '<string id="new_value"' in blob:
            HAS_NAME.add(uid)
        if pm.group(1) == PNTI_PROP and '<record id="new_value">' in blob:
            HAS_NAT.add(uid)
    # Only persons with a name somewhere (MASTER or FM21 export) are promoted: a missing person
    # without any name would be created as a nameless ghost (seen at Roma, 2026-11-26).
    out = {}
    for u in seen:
        if u in created:
            continue
        if u in HAS_NAME or str(u // MULT) in EXPORT:
            out[u] = "2" if u in player else "1"
        else:
            stats["promote_skipped_nameless"] += 1
    return out


