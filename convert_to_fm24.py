def load_export():
    rows = {}
    for path in EXPORT_FILES:
        if not os.path.exists(path):
            continue
        hdr = None
        for line in open(path, encoding="utf-8"):
            if not line.startswith("|") or set(line.strip()) <= set("|- "):
                continue
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if hdr is None:
                hdr = cells
                continue
            if cells == hdr:
                continue
            r = dict(zip(hdr, cells))
            name = re.sub(r"\s+-\s+\S+$", "", r.get("Nome", "")).strip()   # "Christian Vieri - Italiano"
            if r.get("IDU", "").isdigit() and name and name != "-":
                rows.setdefault(r["IDU"], {"name": name, "nac": r.get("Nac", "").strip()})
    return rows


def learn_nation_codes(path):
    """3-letter export code → Nnat id, learned (majority vote) from the patch's own nationality
    records of exported persons. Never guessed."""
    votes = {}
    for blob in stream_records(path):
        if f'property" value="{PNTI_PROP}"' not in blob:
            continue
        m = re.search(r'<record id="new_value">\s*(?:<unsigned id="id" value="\d+"/>\s*)?<integer id="Nnat" value="(\d+)"', blob)
        if not m:
            continue
        eid = str(int(UID_LINE_RE.search(blob).group(2)) & LOW32)
        row = EXPORT.get(eid)
        if row and row["nac"]:
            votes.setdefault(row["nac"], Counter())[int(m.group(1))] += 1
    out = dict(CONFIRMED_NATION_CODES)
    for code, c in votes.items():
        nnat, n = c.most_common(1)[0]
        if n >= 2 and n >= 0.8 * sum(c.values()):
            out[code] = nnat
    return out


